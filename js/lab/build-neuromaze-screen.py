"""Builds js/lab/neuromaze-screen.js: the NeuroMaze gameplay capture as a data
URI, cropped to the lab monitor's 5:3 screen.

WebGL refuses to read local image files when the site is opened from disk
(file://), so the capture travels inside the bundle instead of being fetched.
Requires Pillow. Run from the repository root:

    python js/lab/build-neuromaze-screen.py

then rebuild the bundle (see README.md).
"""
import base64
import io
from pathlib import Path

from PIL import Image

SOURCE = Path('assets/neuromaze-capture.webp')
OUTPUT = Path('js/lab/neuromaze-screen.js')
WIDTH, HEIGHT = 800, 480  # the monitor's screen is 1.0 x 0.6

image = Image.open(SOURCE).convert('RGB')
w, h = image.size
crop_w = min(w, round(h * WIDTH / HEIGHT))
left = (w - crop_w) // 2
image = image.crop((left, 0, left + crop_w, h)).resize((WIDTH, HEIGHT), Image.LANCZOS)
buffer = io.BytesIO()
image.save(buffer, 'WEBP', quality=84, method=6)
data = base64.b64encode(buffer.getvalue()).decode('ascii')
OUTPUT.write_text(
    '// Generated by build-neuromaze-screen.py from assets/neuromaze-capture.webp.\n'
    '// Do not edit: rebuild from the source image.\n'
    f"export const NEUROMAZE_SCREEN = 'data:image/webp;base64,{data}';\n",
    encoding='utf-8', newline='\n')
print(f'{OUTPUT}: {len(data) / 1024:.1f} KB of base64')
